-- ====================================================================
-- Magnetic Analysis: Compare the measure values by categories.
-- It help us understand the importance of different categories. 
-- ====================================================================

-- Find total customer by the countries
SELECT Country,
COUNT(customer_key) AS Total_Customer
FROM dim_customers
GROUP BY Country
ORDER BY Total_customer DESC;

-- Find total customers by gender
SELECT Gender,
COUNT(customer_key) AS Total_Customer
FROM dim_customers
GROUP BY Gender
ORDER BY Total_customer DESC;

-- Find total product by category
SELECT Categroy,
COUNT(Product_Key) AS Total_product
FROM dim_products
GROUP BY Categroy
ORDER BY Total_product DESC;

-- What is the average costs in each category?
SELECT Categroy,
ROUND(Avg(cost),0) AS Avg_Cost
FROM dim_products
GROUP BY Categroy
ORDER BY Avg_Cost DESC;
-- What is the total revenue generated for each category?
SELECT p. categroy,
SUM(sales_amount) Total_Revenue
FROM fact_sales f
LEFT JOIN dim_products p  
ON f.product_Key = p.product_key
GROUP BY Categroy
ORDER BY Total_Revenue DESC;

-- Find total revenue is generated by each customer 
SELECT 
customer_Id,
First_Name,
Last_Name,
SUM(Sales_amount) Total_Revenue
FROM fact_sales f
LEFT JOIN dim_customers c
ON f.customer_Key = c.customer_Key
GROUP BY customer_Id,
First_Name,
Last_Name
ORDER BY Total_Revenue DESC;

-- What is the distribution of sold items across countries?
SELECT 
country,
SUM(quantity) Total_Quantity
FROM fact_sales f
LEFT JOIN dim_customers c
ON f.customer_Key = c.customer_Key
GROUP BY country
ORDER BY Total_Quantity DESC;

-- ====================================================================
-- Ranking Analysis: Order the value of Dimensions by measure.
-- Top N Performers | Bottom N Performers 
-- ====================================================================

-- Which 5 products generate the Highest revenue?
SELECT p. product_Name,
SUM(sales_amount) Total_Revenue
FROM fact_sales f
LEFT JOIN dim_products p  
ON f.product_Key = p.product_key
GROUP BY product_Name
ORDER BY Total_Revenue DESC
Limit 5;

-- 2ND METHOD (USING WINDOW FUNCTION)

SELECT * FROM (
SELECT p. product_Name,
SUM(sales_amount) Total_Revenue,
ROW_NUMBER() OVER(ORDER BY SUM(sales_amount) DESC) AS Row_Num
FROM fact_sales f
LEFT JOIN dim_products p  
ON f.product_Key = p.product_key
GROUP BY product_Name)t
WHERE Row_Num <= 5;

-- what are the 5 worst-performing products in terms of sales?
SELECT p. product_Name,
SUM(sales_amount) Total_Revenue
FROM fact_sales f
LEFT JOIN dim_products p  
ON f.product_Key = p.product_key
GROUP BY product_Name
ORDER BY Total_Revenue ASC
Limit 5;


-- Find the top 10 customers who have generated the highest revenue 
SELECT 
customer_Id,
First_Name,
Last_Name,
SUM(Sales_amount) Total_Revenue,
ROW_NUMBER() OVER(ORDER BY SUM(Sales_amount) DESC) Highest_Revenue
FROM fact_sales f
LEFT JOIN dim_customers c
ON f.customer_Key = c.customer_Key
GROUP BY customer_Id,
First_Name,
Last_Name
ORDER BY Total_Revenue DESC
LIMIT 10;

