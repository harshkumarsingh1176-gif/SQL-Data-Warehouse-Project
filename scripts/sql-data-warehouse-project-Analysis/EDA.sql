-- Find the date of the First and Lasr order
SELECT MIN(Order_date) first_order_date,
MAX(Order_date) last_order_date,
round((DATEDIFF( MAX(order_date),MIN(order_date))/365),0) Order_Range_Years,
TIMESTAMPDIFF(Month, MIN(order_date), MAX(order_date)) AS Order_Range_Month
FROM fact_sales;

-- Find the youngest and oldest customer 
SELECT MIN(Birthdate) Oldest_Birthdate,
TIMESTAMPDIFF(Year, MIN(Birthdate), CURRENT_DATE()) AS Oldest_age,
MAX(Birthdate) Youngest_Birthdate,
TIMESTAMPDIFF(Year, MAX(Birthdate), CURRENT_DATE()) AS Youngest_age
FROM dim_customers;

